#!/usr/bin/env python
"""
Turn a system description (systems/<name>.yaml) into a ready-to-run PACSim
directory (runs/<name>/) containing the CIF, configuration.yaml and run.yaml.

    python build.py systems/cscl.yaml
    python build.py systems/cscl.yaml --debye 4.1 --tag melt_some

pacsim-create reads configuration.yaml (and reaches into run.yaml for the
potential parameters it needs to optimize the lattice spacing), pacsim-run reads
run.yaml. Both are generated here so the two files can never drift apart.
"""
import argparse
import shutil
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent

CONFIGURATION_TEMPLATE = """\
# Generated by build.py from {source}. Do not edit by hand.
configuration_generator: LatticeBuilder
configuration_generator_parameters:
  lattice_specification: {cif}
  lattice_repeats: {lattice_repeats}
  run_parameters_file: run.yaml
  radii_padding: !Quantity
    unit: nanometer
    value: {radii_padding_nm}
  lattice_padding: !Quantity
    unit: nanometer
    value: {lattice_padding_nm}
  optimize_energy: {optimize_energy}
  energy_scale_range: [{scale_min}, {scale_max}]
  energy_scale_samples: {energy_scale_samples}
{anisotropic_block}\
masses:
{masses_block}\
radii:
{radii_block}\
surface_potentials:
{potentials_block}\
initial_modifiers: null
initial_modifiers_parameters: null
final_modifiers: null
final_modifiers_parameters: null
"""

RUN_TEMPLATE = """\
# Generated by build.py from {source}. Do not edit by hand.
initial_configuration: first_frame.gsd
platform_name: {platform}

# --- potential ---------------------------------------------------------------
potential_temperature: !Quantity
  unit: kelvin
  value: {potential_temperature_K}
debye_length: !Quantity
  unit: nanometer
  value: {debye_length_nm}
brush_length: !Quantity
  unit: nanometer
  value: {brush_length_nm}
brush_density: !Quantity
  unit: /(nanometer**2)
  value: {brush_density_per_nm2}
dielectric_constant: {dielectric_constant}
cutoff_factor: {cutoff_factor}
steric_radius_average: harmonic
electrostatic_radius_average: harmonic
use_log: false

# --- integrator --------------------------------------------------------------
integrator: LangevinIntegrator
integrator_parameters:
  temperature: !Quantity
    unit: kelvin
    value: {integrator_start_T}
  frictionCoeff: !Quantity
    unit: /picosecond
    value: {friction_per_ps}
  stepSize: !Quantity
    unit: picosecond
    value: {timestep_ps}
  randomNumberSeed: {seed}
velocity_seed: {seed}
minimize_energy_initially: false
run_steps: {run_steps}

# --- temperature schedule ----------------------------------------------------
{ramp_block}\

# --- walls / gravity ---------------------------------------------------------
wall_directions:
{walls_block}\
epsilon: !Quantity
  unit: kilojoule/mole
  value: 2.477709860209665  # 1 k_B T
alpha: 1.0
use_gravity: {use_gravity}
gravitational_acceleration: !Quantity
  unit: meter/(second**2)
  value: 9.8
particle_density: !Quantity
  unit: gram/(centimeter**3)
  value: {particle_density_g_per_cm3}
water_density: !Quantity
  unit: gram/(centimeter**3)
  value: {water_density_g_per_cm3}

# --- unused physics ----------------------------------------------------------
use_depletion: false
depletant_radius: null
depletion_phi: null
use_implicit_substrate: false
substrate_wall_charge: null
use_plumed: false
plumed_script: null

# --- output ------------------------------------------------------------------
trajectory_filename: trajectory.gsd
trajectory_interval: {trajectory_interval}   # {n_frames} frames
state_data_filename: state_data.csv
state_data_interval: {state_data_interval}
checkpoint_filename: checkpoint.chk
checkpoint_interval: {checkpoint_interval}
final_configuration_gsd_filename: final_frame.gsd
"""


RAMP_BLOCK = """\
# Ramped: integrator T goes start -> target over ramp_steps. Only the INTEGRATOR
# temperature is ramped; the potential stays at potential_temperature throughout.
update_reporter: RampTemperatureUpdateReporter
update_reporter_parameters:
  filename: ramp.csv
  update_interval: 500
  print_interval: {state_data_interval}
  final_update_step: {ramp_steps}
  start_value: !Quantity
    unit: kelvin
    value: {start_temperature_K}
  end_value: !Quantity
    unit: kelvin
    value: {potential_temperature_K}
"""

NO_RAMP_BLOCK = """\
# NO RAMP. The integrator starts at the target temperature ({potential_temperature_K} K)
# from step 0, with velocities drawn from Maxwell-Boltzmann at that temperature.
# A genuinely stable crystal should survive an instantaneous start at temperature; the
# ramp was only ever there to stop a spurious dissolve, and it costs interpretability
# (it makes the first ~40% of the trajectory a transient rather than an equilibrium run).
update_reporter: null
update_reporter_parameters: null
"""


def quantity_block(types, key, unit_name, indent="  "):
    lines = []
    for type_name, values in types.items():
        lines.append(f'{indent}"{type_name}": !Quantity\n')
        lines.append(f"{indent}  unit: {unit_name}\n")
        lines.append(f"{indent}  value: {values[key]}\n")
    return "".join(lines)


def render_fields(system, source, cif_name):
    """Expand a system dict into the substitutions used by both YAML templates."""
    run_steps = int(system["run_steps"])
    n_frames = int(system["n_frames"])
    if run_steps % n_frames != 0:
        raise SystemExit(f"run_steps ({run_steps}) must be divisible by n_frames ({n_frames})")
    trajectory_interval = run_steps // n_frames

    return dict(
        source=source,
        cif=cif_name,
        lattice_repeats=system["lattice_repeats"],
        radii_padding_nm=system["radii_padding_nm"],
        lattice_padding_nm=system["lattice_padding_nm"],
        optimize_energy=str(bool(system["optimize_energy"])).lower(),
        # anisotropic_energy relaxes each symmetry-distinct axis separately instead of
        # applying one uniform scale. It is a no-op for cubic cells (one free parameter
        # either way) and required for everything else, whose CIF axial ratios describe
        # an ATOMIC crystal and are generally wrong for colloids of the same structure
        # type. Emitted only when set, so pre-existing configuration.yaml files that
        # never carried the key are reproduced byte-for-byte. Needs PACSim >= 582a2d0.
        anisotropic_block=("  anisotropic_energy: true\n"
                           if system.get("anisotropic_energy") else ""),
        scale_min=system["energy_scale_range"][0],
        scale_max=system["energy_scale_range"][1],
        energy_scale_samples=system["energy_scale_samples"],
        masses_block=quantity_block(system["types"], "mass_dalton", "dalton"),
        radii_block=quantity_block(system["types"], "radius_nm", "nanometer"),
        potentials_block=quantity_block(system["types"], "surface_potential_mV", "millivolt"),
        platform=system["platform"],
        potential_temperature_K=system["potential_temperature_K"],
        start_temperature_K=system["start_temperature_K"],
        integrator_start_T=(system["start_temperature_K"] if system.get("use_ramp", True)
                            else system["potential_temperature_K"]),
        ramp_block=(RAMP_BLOCK.format(
            state_data_interval=max(1, (int(system["run_steps"]) // int(system["n_frames"])) // 10),
            ramp_steps=system["ramp_steps"],
            start_temperature_K=system["start_temperature_K"],
            potential_temperature_K=system["potential_temperature_K"])
            if system.get("use_ramp", True) else NO_RAMP_BLOCK.format(
                potential_temperature_K=system["potential_temperature_K"])),
        debye_length_nm=system["debye_length_nm"],
        brush_length_nm=system["brush_length_nm"],
        brush_density_per_nm2=system["brush_density_per_nm2"],
        dielectric_constant=system["dielectric_constant"],
        cutoff_factor=system["cutoff_factor"],
        friction_per_ps=system["friction_per_ps"],
        timestep_ps=system["timestep_ps"],
        seed=system["seed"],
        run_steps=run_steps,
        ramp_steps=system["ramp_steps"],
        walls_block="".join(f"  - {str(bool(w)).lower()}\n" for w in system["walls"]),
        use_gravity=str(bool(system["use_gravity"])).lower(),
        particle_density_g_per_cm3=system["particle_density_g_per_cm3"],
        water_density_g_per_cm3=system["water_density_g_per_cm3"],
        trajectory_interval=trajectory_interval,
        n_frames=n_frames,
        state_data_interval=max(1, trajectory_interval // 10),
        checkpoint_interval=trajectory_interval * 10,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("system", type=Path, help="systems/<name>.yaml")
    parser.add_argument("--debye", type=float, default=None,
                        help="override debye_length_nm (for melting scans)")
    parser.add_argument("--repeats", type=int, default=None,
                        help="override lattice_repeats (for quick tests)")
    parser.add_argument("--steps", type=int, default=None, help="override run_steps")
    parser.add_argument("--frames", type=int, default=None, help="override n_frames")
    parser.add_argument("--platform", default=None, help="override platform (CPU/CUDA)")
    parser.add_argument("--seed", type=int, default=None, help="override seed")
    parser.add_argument("--tag", default=None,
                        help="suffix for the run directory, e.g. runs/<name>_<tag>")
    args = parser.parse_args()

    system = yaml.safe_load(args.system.read_text())
    if args.debye is not None:
        system["debye_length_nm"] = args.debye
    if args.repeats is not None:
        system["lattice_repeats"] = args.repeats
    if args.steps is not None:
        system["run_steps"] = args.steps
    if args.frames is not None:
        system["n_frames"] = args.frames
    if args.platform is not None:
        system["platform"] = args.platform
    if args.seed is not None:
        system["seed"] = args.seed

    run_name = system["name"] if args.tag is None else f"{system['name']}_{args.tag}"
    run_dir = HERE / "runs" / run_name
    run_dir.mkdir(parents=True, exist_ok=True)

    # cif_dir lets a system point at the deduplicated cif_library instead of
    # structures/. Defaults to structures/ so existing systems are unaffected.
    cif_dir = Path(system.get("cif_dir") or (HERE / "structures"))
    if not cif_dir.is_absolute():
        cif_dir = HERE / cif_dir
    cif_source = cif_dir / system["cif"]
    if not cif_source.is_file():
        raise SystemExit(f"CIF not found: {cif_source}")
    shutil.copy(cif_source, run_dir / cif_source.name)

    fields = render_fields(system, args.system.name, cif_source.name)
    run_steps, n_frames = fields["run_steps"], fields["n_frames"]
    trajectory_interval = fields["trajectory_interval"]

    (run_dir / "configuration.yaml").write_text(CONFIGURATION_TEMPLATE.format(**fields))
    (run_dir / "run.yaml").write_text(RUN_TEMPLATE.format(**fields))

    print(f"wrote {run_dir}/configuration.yaml")
    print(f"wrote {run_dir}/run.yaml")
    print(f"  {system['lattice_repeats']}^3 cells, debye = {system['debye_length_nm']} nm, "
          f"{run_steps} steps, {n_frames} frames (every {trajectory_interval})")
    print(f"\nnext:\n  cd {run_dir}\n  pacsim-create configuration.yaml first_frame.gsd\n  pacsim-run run.yaml")


if __name__ == "__main__":
    main()
